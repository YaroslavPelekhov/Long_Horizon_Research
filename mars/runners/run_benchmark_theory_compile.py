def _read_text(path: Path, *, max_chars: int = 50000) -> str:
    if not path.exists():
        return ""
    text = path.read_text(encoding="utf-8", errors="ignore")
    return text[:max_chars]


def _extract_section(text: str, benchmark_name: str) -> str:
    """Extract benchmark-specific markdown sections from shared audit docs."""

    if not text or benchmark_name not in text:
        return text
    lines = text.splitlines()
    starts = [
        i
        for i, line in enumerate(lines)
        if line.lstrip().startswith("#") and benchmark_name.lower() in line.lower()
    ]
    if not starts:
        return text
    chunks: list[str] = []
    for start in starts:
        level = len(lines[start]) - len(lines[start].lstrip("#"))
        end = len(lines)
        for j in range(start + 1, len(lines)):
            stripped = lines[j].lstrip()
            if stripped.startswith("#"):
                next_level = len(stripped) - len(stripped.lstrip("#"))
                if next_level <= level:
                    end = j
                    break
        chunks.append("\n".join(lines[start:end]))
    return "\n\n".join(chunks)


def _read_json(path: Path) -> dict[str, Any]:
    if not path.exists():
        return {"missing": str(path)}
    try:
        return json.loads(path.read_text(encoding="utf-8", errors="ignore"))
    except Exception as exc:
        return {"path": str(path), "error": f"{type(exc).__name__}: {exc}"}


def _sources_for(name: str) -> dict[str, str]:
    sources: dict[str, str] = {}
    for rel in BENCHMARK_SOURCES[name]:
        path = _PROJ / rel
        text = _read_text(path)
        if text:
            if rel.startswith("BENCHMARK_") or rel.startswith("GPT4O_"):
                text = _extract_section(text, name)
            sources[rel] = text
    return sources


def _prior_for(name: str) -> dict[str, Any]:
    return {rel: _read_json(_PROJ / rel) for rel in PRIOR_SUMMARIES.get(name, ())}


def _theory_markdown(theories: list[BenchmarkTheory]) -> str:
    lines = [
        "# Self-Induced Benchmark Theories",
        "",
        "This file is generated by `mars.runners.run_benchmark_theory_compile`.",
        "It is a benchmark-interface map, not a final benchmark score table.",
        "",
        "| Benchmark | Theory ID | Confidence | Task object | Metrics | Actions | Residuals | Skills |",
        "|---|---|---:|---|---|---|---|---|",
    ]
    for theory in theories:
        metrics = ", ".join(m.name for m in theory.metrics)
        actions = ", ".join(a.name for a in theory.actions)
        residuals = ", ".join(r.name for r in theory.residuals)
        skills = ", ".join(s.name for s in theory.skill_schemas)
        lines.append(
            f"| {theory.benchmark_name} | `{theory.theory_id}` | {theory.confidence:.3f} | "
            f"{theory.task_object} | {metrics} | {actions} | {residuals} | {skills} |"
        )
    lines += [
        "",
        "## Compression Objective",
        "",
        "All compiled theories use the same objective:",
        "",
        "```text",
        "argmin_T L(interface_T) + L(action_grammar_T) + L(verifier_graph_T) + L(residuals | T)",
        "promote skill iff program_bits(skill) + residual_bits_after < residual_bits_before",
        "```",
        "",
        "## Per-Benchmark Details",
        "",
    ]
    for theory in theories:
        lines += [
            f"### {theory.benchmark_name}",
            "",
            f"- Task object: {theory.task_object}",
            f"- Observable inputs: {', '.join(theory.observable_inputs)}",
            f"- Target outputs: {', '.join(theory.target_outputs)}",
            f"- Metrics: {', '.join(m.name for m in theory.metrics)}",
            f"- Residual classes: {', '.join(r.name for r in theory.residuals)}",
            f"- Skill schemas: {', '.join(s.name for s in theory.skill_schemas)}",
            "",
        ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--run_id", default="four_benchmark_theory_20260618")
    parser.add_argument("--overwrite", action="store_true")
    args = parser.parse_args()

    out_dir = _PROJ / "lmw" / "benchmark_theory" / args.run_id
    out_dir.mkdir(parents=True, exist_ok=True)
    json_path = out_dir / "theories.json"
    md_path = out_dir / "theories.md"
    if (json_path.exists() or md_path.exists()) and not args.overwrite:
        raise SystemExit(f"output exists; pass --overwrite: {out_dir}")

    theories = [
        compile_benchmark_theory(name, _sources_for(name), prior_results=_prior_for(name))
        for name in BENCHMARK_SOURCES
    ]
    payload = {
        "run_id": args.run_id,
        "n": len(theories),
        "theories": [t.to_dict() for t in theories],
    }
    json_path.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")
    md_path.write_text(_theory_markdown(theories), encoding="utf-8")

    print("=== benchmark theory compile ===")
    for theory in theories:
        print(
            f"{theory.benchmark_name}: id={theory.theory_id} "
            f"confidence={theory.confidence:.3f} "
            f"metrics={','.join(m.name for m in theory.metrics)} "
            f"residuals={','.join(r.name for r in theory.residuals)}"
        )
    print(f"json={json_path}")
    print(f"md={md_path}")


if __name__ == "__main__":
    main()
